// Builds the bundled copy of Terms / Privacy / Disclaimer from content/legal/*.txt
//   -> src/generated/legal.js        (so the pages work offline from the very first launch)
//   -> supabase/seed_legal.sql       (so the same text can be loaded into the database)
//
// Run:  npm run legal      (also runs automatically before `npm run build`)
// Env:  APP_NAME_EN / APP_NAME_BN, VITE_SUPPORT_EMAIL, LEGAL_EFFECTIVE_DATE (YYYY-MM-DD)

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { parseBlocks } from '../src/lib/text.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SLUGS = ['disclaimer', 'terms', 'privacy'];
const DEFAULT_DATE = '2026-10-22';

const EN_MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];
const BN_MONTHS = ['জানুয়ারি', 'ফেব্রুয়ারি', 'মার্চ', 'এপ্রিল', 'মে', 'জুন', 'জুলাই', 'আগস্ট', 'সেপ্টেম্বর', 'অক্টোবর', 'নভেম্বর', 'ডিসেম্বর'];
const BN_DIGITS = ['০', '১', '২', '৩', '৪', '৫', '৬', '৭', '৮', '৯'];
const toBn = (s) => String(s).replace(/[0-9]/g, (d) => BN_DIGITS[Number(d)]);

export function formatEffectiveDate(iso) {
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(iso || '');
  if (!m) throw new Error(`LEGAL_EFFECTIVE_DATE must be YYYY-MM-DD, got "${iso}"`);
  const [, y, mo, d] = m;
  const mi = Number(mo) - 1;
  if (mi < 0 || mi > 11) throw new Error(`Invalid month in "${iso}"`);
  return { en: `${Number(d)} ${EN_MONTHS[mi]} ${y}`, bn: `${toBn(Number(d))} ${BN_MONTHS[mi]} ${toBn(y)}` };
}

/** Replace {{PLACEHOLDERS}}; unknown placeholders are an error so typos never ship. */
export function fillPlaceholders(text, vars) {
  return text.replace(/\{\{([A-Z_]+)\}\}/g, (_, key) => {
    if (!(key in vars)) throw new Error(`Unknown placeholder {{${key}}}`);
    return vars[key];
  });
}

export function buildVars(lang, env = process.env) {
  const date = formatEffectiveDate(env.LEGAL_EFFECTIVE_DATE || DEFAULT_DATE);
  const email = (env.VITE_SUPPORT_EMAIL || '').trim();
  return {
    APP_NAME: lang === 'bn' ? env.APP_NAME_BN || 'আইন জমি' : env.APP_NAME_EN || 'Ain Jomi',
    EFFECTIVE_DATE: date[lang],
    SUPPORT_EMAIL: email || (lang === 'bn' ? 'অ্যাপে দেওয়া যোগাযোগের ঠিকানা' : 'the support contact shown in the app'),
  };
}

export function loadPages(root = ROOT, env = process.env) {
  const pages = {};
  for (const slug of SLUGS) {
    const page = { version: 1, title: {}, body: {} };
    for (const lang of ['bn', 'en']) {
      const raw = readFileSync(join(root, 'content', 'legal', `${slug}.${lang}.txt`), 'utf8').replace(/\r\n?/g, '\n').trim();
      const filled = fillPlaceholders(raw, buildVars(lang, env));
      page.title[lang] = filled.split('\n')[0].trim();
      page.body[lang] = filled;
    }
    pages[slug] = page;
  }
  return pages;
}

/** SQL string literal using a dollar-quote tag that cannot appear in the text. */
export function sqlText(value) {
  let tag = 'aj';
  while (value.includes(`$${tag}$`)) tag += 'x';
  return `$${tag}$${value}$${tag}$`;
}

export function toSeedSql(pages) {
  const rows = SLUGS.map((slug) => {
    const p = pages[slug];
    return `  ('${slug}', ${sqlText(p.title.bn)}, ${sqlText(p.title.en)}, ${sqlText(p.body.bn)}, ${sqlText(p.body.en)}, ${p.version}, 'published')`;
  });
  return [
    '-- GENERATED by scripts/build-legal.mjs from content/legal/*.txt. Do not edit by hand.',
    '-- Safe to re-run: existing rows are left alone, so edits made in the admin panel are never overwritten.',
    'insert into public.legal_pages (slug, title_bn, title_en, body_bn, body_en, version, status) values',
    rows.join(',\n'),
    'on conflict (slug) do nothing;',
    '',
  ].join('\n');
}

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

function blocksToHtml(text) {
  const out = [];
  let inList = false;
  for (const b of parseBlocks(text)) {
    if (b.type !== 'li' && inList) {
      out.push('</ul>');
      inList = false;
    }
    if (b.type === 'title') out.push(`<h2>${esc(b.text)}</h2>`);
    else if (b.type === 'h') out.push(`<h3>${esc(b.text)}</h3>`);
    else if (b.type === 'li') {
      if (!inList) {
        out.push('<ul>');
        inList = true;
      }
      out.push(`<li>${esc(b.text)}</li>`);
    } else out.push(`<p>${esc(b.text)}</p>`);
  }
  if (inList) out.push('</ul>');
  return out.join('\n');
}

/** Public, crawlable page (Google Play needs a privacy-policy URL). Both languages on one page. */
export function toStaticHtml(slug, page) {
  const title = `${page.title.bn} · ${page.title.en}`;
  return `<!doctype html>
<html lang="bn">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>${esc(title)}</title>
    <link rel="stylesheet" href="../site.css" />
  </head>
  <body>
    <main class="site">
      <nav class="site-nav" aria-label="Language"><a href="#bn">বাংলা</a><a href="#en">English</a><a href="../">Home</a></nav>
      <article class="doc" id="bn" lang="bn">
${blocksToHtml(page.body.bn)}
      </article>
      <article class="doc" id="en" lang="en">
${blocksToHtml(page.body.en)}
      </article>
    </main>
  </body>
</html>
`;
}

export function toModule(pages) {
  return `// GENERATED by scripts/build-legal.mjs from content/legal/*.txt. Do not edit by hand.\nexport const LEGAL = ${JSON.stringify(pages, null, 2)};\n`;
}

function main() {
  const pages = loadPages();
  mkdirSync(join(ROOT, 'src', 'generated'), { recursive: true });
  writeFileSync(join(ROOT, 'src', 'generated', 'legal.js'), toModule(pages));
  writeFileSync(join(ROOT, 'supabase', 'seed_legal.sql'), toSeedSql(pages));
  for (const slug of ['privacy', 'terms']) {
    mkdirSync(join(ROOT, 'web', slug), { recursive: true });
    writeFileSync(join(ROOT, 'web', slug, 'index.html'), toStaticHtml(slug, pages[slug]));
  }
  console.log(`legal: wrote ${SLUGS.length} pages x 2 languages`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
