// Builds supabase/ALL_IN_ONE.sql: every database script in the right order, in ONE file you paste once into the
// Supabase SQL Editor. Safe to run again at any time:
//   - things that already exist are left as they are (admin edits to Terms/Privacy are never overwritten),
//   - things that are new are added,
//   - the old phase5_lawyers.sql step is skipped automatically once phase 5 version 2 is in place.
// When a new phase adds a .sql file, add it to PARTS below and run `npm run sql`.

import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (f) => readFileSync(join(ROOT, 'supabase', f), 'utf8').replace(/\r\n/g, '\n').trimEnd();

export function buildAllSql() {
  const v1 = read('phase5_lawyers.sql');
  if (v1.includes('$v1$')) throw new Error('phase5_lawyers.sql must not contain the quote tag $v1$');
  const part = (title, body) => `-- =====================================================================\n-- ${title}\n-- =====================================================================\n${body}\n`;
  return [
    '-- Ain Jomi: ALL database scripts in one file. GENERATED by scripts/build-sql.mjs. Do not edit by hand.',
    '-- Paste the whole file into Supabase > SQL Editor and press Run. Safe to run again: existing data and settings stay,',
    '-- missing parts are added.',
    '',
    part('1. Foundation (schema.sql)', read('schema.sql')),
    part('2. Terms, Privacy and Disclaimer text (seed_legal.sql): only adds pages that are missing', read('seed_legal.sql')),
    part(
      '3. Phase 5, lawyer directory, first version (phase5_lawyers.sql): skipped when version 2 is already there',
      `do $phase5v1$\nbegin\n  if not exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'lawyer_profiles' and column_name = 'certificate_paths') then\n    execute $v1$\n${v1}\n$v1$;\n  end if;\nend $phase5v1$;`,
    ),
    part('4. Phase 5 version 2 (phase5_lawyers_v2.sql): certificates, paid contact, paid ratings', read('phase5_lawyers_v2.sql')),
    part('5. Phase 6, AI assistant (phase6_ai.sql)', read('phase6_ai.sql')),
    "select 'Ain Jomi database is up to date' as result;",
    '',
  ].join('\n');
}

if (import.meta.url === pathToFileURL(process.argv[1] || '').href) {
  writeFileSync(join(ROOT, 'supabase', 'ALL_IN_ONE.sql'), buildAllSql());
  console.log('sql: supabase/ALL_IN_ONE.sql written');
}
